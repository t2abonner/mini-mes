import { randomUUID } from 'node:crypto';

/**
 * Непрозрачный токен: случайная строка без полезной нагрузки.
 *
 * В отличие от JWT, токен не содержит ни пользователя, ни срока —
 * это лишь ключ, по которому сервер находит запись сессии в памяти
 * (см. аналогию с гардеробным номерком).
 *
 * Для стенда хватает случайного UUID (122 бита энтропии).
 * В реальном бэкенде чаще берут `crypto.randomBytes(32).toString('hex')`.
 */
export const generateToken = (): string => randomUUID();
